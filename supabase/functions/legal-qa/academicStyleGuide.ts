// Injected verbatim into Deep `write_chapter` drafts (real body chapters only;
// not abstract / introduction / conclusion / outline / validate / topics).
//
// v1 source of truth: derived from a stratified sample of ~150 journal_article
// documents in `legal_documents`, distilled by gpt-5 and human-reviewed.
// Update procedure: run `node eval/distill-style-guide.mjs` → review draft
// → replace ACADEMIC_STYLE_GUIDE below → bump ACADEMIC_STYLE_GUIDE_VERSION.
