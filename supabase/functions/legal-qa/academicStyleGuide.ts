export const ACADEMIC_STYLE_GUIDE_VERSION = "v1.0-bootstrap";

// NOTE: this v1.0-bootstrap text is a placeholder distilled by hand from the
// existing academic profile patterns and Hebrew legal-academic conventions,
// pending the full corpus-derived v1 (run `eval/distill-style-guide.mjs`).
// It is prescriptive (אסור / יש / רצוי), not descriptive, on purpose.
export const ACADEMIC_STYLE_GUIDE = `**1. קצב פסקה ומשפט פותח**
- פסקה אקדמית טיפוסית: 4–7 משפטים. פסקאות של משפט אחד אסורות; פסקאות של 10+ משפטים מעידות על שתי טענות שלא הופרדו.
- משפט פותח של פסקה ממקם את הטענה (topic sentence): "הטענה המרכזית בפרק זה היא…", "במישור הדוקטרינרי, …", "מנקודת מבט נורמטיבית, …".
- אין לפתוח פסקה ב"לכן" / "לפיכך" / "כך" — אלה מילות קישור פנים־פסקתיות, לא פתיחה.
- אורך משפט ממוצע: 18–28 מילים. משפטים קצרים מ־8 מילים מותרים רק לסיכום או להדגשה דרמטית, ולא יותר ממשפט קצר אחד לפסקה.

**2. מהלכי פתיחה (לפסקאות וסעיפים)**
- "הטענה המרכזית של חלק זה היא X. כדי לבססה, נבחן…"
- "הדיון להלן מתפרס על שלושה מישורים: דוקטרינרי, נורמטיבי והשוואתי."
- "נקודת המוצא הדוקטרינרית היא…"
- "השאלה שעולה במצב דברים זה היא…"
- אסור: "במאמר זה נראה ש…" כפתיחה לפסקת ביניים. הכרזות־על מותרות רק במבוא ובסיכום, לא בגוף הפרק.

**3. מהלכי קישור (transitions)**
- *הסכמה־עם־הסתייגות*: "אכן, X. ואולם, …"; "ניתן להסכים ל־X, אך לא ל־Y, משום ש…"
- *חידוד*: "ליתר דיוק, …"; "במונחים מדויקים יותר, …"; "ראוי לאבחן בין X לבין Y."
- *פיווט דוקטרינרי*: "המקור הדוקטרינרי לעמדה זו הוא…"; "בית המשפט בעניין X קבע ש…, ובכך…"
- *מהלך השוואתי*: "במשפט המשווה, גישה דומה / שונה אומצה ב…"
- *סינתזה*: "צירוף שני הקווים שהוצגו לעיל מוביל למסקנה ש…"
- אסור: "בנוסף", "כמו כן" כמהלכים נטולי תוכן בתחילת פסקה. אם משתמשים בהם — חייבים להוסיף עומק (מה בדיוק מתווסף).

**4. טיפול בטיעוני נגד**
- מבנה חובה: *steel-man → distinguish → resolve*. אסור להציג טיעון נגד באופן חלש כדי להפילו ("strawman").
- ניסוח: "הטענה החזקה ביותר נגד עמדתי היא ש־X. ניתן להבחין בין X ל־Y בכך ש… ולפיכך, …"
- כשאין הכרעה חדה: "אין מענה מלא לקושי זה במסגרת הנוכחית; אסתפק כאן בקביעה ש…"
- אסור: לבטל טיעון נגד במשפט אחד או בלעג. רטוריקה משפטית־אקדמית רצינית מתעמתת, לא מבזה.

**5. צפיפות הערות שוליים**
- *פסקה דוקטרינרית* (חוק, פסיקה, תקנה): 2–4 הערות שוליים. כל קביעה דוקטרינרית קונקרטית דורשת אסמכתה.
- *פסקה נורמטיבית* (טיעון של הכותב): 0–2 הערות שוליים — רק להפניות לספרות תומכת או חולקת.
- *פסקה השוואתית*: 1–3 הערות שוליים, לרוב למקור משפט זר אחד מרכזי.
- *פסקאות ביניים שמסכמות* (סוף תת־פרק): לרוב 0 הערות שוליים. הסיכום מסתמך על מה שבוסס לעיל.
- אסור: צפיפות אחידה של 4+ הערות לכל פסקה — סימן ל"קישוט" של פסקה נורמטיבית כאילו היא דוקטרינרית.

**6. מהלכי סיום (לפסקה / לסעיף / לפרק)**
- *סינתזה*: "מצירוף הניתוח לעיל עולה ש…" — מותר; ממקם את הסיכום, לא רק חוזר.
- *שאלה פתוחה*: "סוגיה זו, אף שאינה נדונה כאן במלואה, ראויה לבחינה נפרדת."
- *מסקנה מדיניותית* (נדיר, רק כשמתאים): "מן הניתוח עולה כי ראוי לשקול שינוי חקיקתי ש…"
- אסור: סיום בקלישאה ("עתיד לתת", "ימים יגידו", "תקוותנו ש…"). סיום של פסקה לעולם לא יהיה במשפט שמהותו רגשית בלבד.

**7. רגיסטר ולשון**
- *מותר ורצוי*: "אטען", "אבקש להראות", "ראוי", "מן הראוי", "אבחנה זו", "בענייננו", "עניין X". גוף ראשון רבים אקדמי ("נראה ש…") מותר, אך עקביות חשובה — אל תערבב "אטען" עם "נטען על ידי" באותה יחידת טקסט.
- *להשתמש בזהירות*: "דומני", "סבורני", "נדמה לי" — מבטאים אי־ודאות מכוונת; הופעות 2–3 לפרק 2,000 מילים, לא יותר.
- *אסור*: "אני חושב ש…", "לדעתי האישית", סלנג, מילים לועזיות לא־מתועתקות כשיש מקבילה עברית מקובלת ("argument" → "טיעון"; "scope" → "היקף").
- *זרים*: מונחים משפטיים זרים מקובלים נשמרים בלעז עם תעתיק או תרגום בסוגריים בהופעה ראשונה: "stare decisis (תקדים מחייב)", ואחר כך בלעז בלבד.
- *גוף שלישי על פסיקה*: "בית המשפט קבע…", לא "השופט/ת הנכבד/ת". פסיקה היא מקור משפטי, לא דמות.

**8. אנטי־דפוסים — לעולם לא לעשות**
- *רשימות (bullets) במקום פרוזה*: בכתיבה אקדמית משפטית בעברית, רשימות מותרות רק להצגת קריטריונים מפורשים מכלל משפטי או למיפוי גישות חולקות שהוגדרו בטקסט. להציג שלושה טיעונים שלך כ־bullets — אסור. כתוב פסקת פרוזה.
- *מרכאות־לעג ("scare quotes")* סביב מונחים שאינך מסכים להם — רטוריקה זולה. אם אתה חולק, אבחן או הראה למה המונח מטעה.
- *הכרזות־על בלי תוכן*: "מאמר זה תורם תרומה משמעותית להבנת…" — נסיגה למשמעי. אם יש תרומה, נסח אותה ספציפית.
- *מילות חיזוק ריקות*: "ברור ש…", "אין ספק ש…", "מובן מאליו ש…". אם הטענה ברורה, היא לא דורשת חיזוק. אם אינה ברורה, חיזוק לא יהפוך אותה לכזו.
- *הצהרות "Bluebook" בעברית*: "ראו בהרחבה ב…" כדרך לחמוק מציטוט. אם המקור רלוונטי לטענה — צטט אותו במלואו בהערת שוליים.
- *פתיחת פסקה במילה אנגלית* או בקיצור לועזי לא־מסומן.
- *סיום סעיף במשפט שמתחיל ב"לסיכום" או "לפיכך"* כתחליף לעבודת סינתזה אמיתית.
`;

/**
 * Build the prompt-injectable style block. The header explicitly fences the
 * content as non-source so the drafter does not pull phrasing or treat any
 * line as a citable proposition.
 */
export function buildStyleGuideBlock(): string {
  return `כללי סגנון אקדמי — לא מקור לציטוט (גרסה ${ACADEMIC_STYLE_GUIDE_VERSION})\n` +
    `אסור לצטט, להפנות, להעתיק או לשבץ פראזה כלשהי מהבלוק הזה. הוא מתאר תבניות בלבד; כל פסקה שתיכתב חייבת להישען על המקורות מבלוק "מקורות" בלבד.\n\n` +
    ACADEMIC_STYLE_GUIDE;
}

// Runtime sanity guard. ~12,000 chars ≈ 3,000 Hebrew tokens.
if (ACADEMIC_STYLE_GUIDE.length > 12000) {
  console.warn(
    `[academicStyleGuide] ACADEMIC_STYLE_GUIDE exceeds 12,000 chars ` +
    `(${ACADEMIC_STYLE_GUIDE.length}); style instructions cap is 3,000 tokens. ` +
    `Trim the guide before shipping.`,
  );
}
