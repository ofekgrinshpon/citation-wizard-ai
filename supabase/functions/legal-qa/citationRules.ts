export function buildCitationInstructions(): string {
  let output = `כללי כתיבה להערות שוליים — כללי האזכור האחיד (2021)

══ כללים כלליים ══
• כלל 1.9 (הפרדה בפסיק): כאשר שני מספרים או שתי מילים עוקבים ללא הבחנה עיצובית — חובה להפריד בפסיק.
• כלל 1.10 (טווחי מספרים): בעברית מימין לשמאל: 37–40, כה–כז. בלועזית: לפי שפת המקור.
• כלל 23.2.3 (איסור תוארים): אין לציין תואר אקדמי, צבאי או מקצועי של מחבר — לא פרופ', ד"ר, עו"ד, רו"ח, שופט, המנוח, ז"ל. שם פרטי ושם משפחה בלבד.
• כלל 23.2.4: מוסד כמחבר — שם המוסד בלבד, ללא שמות חברים. דוחות ועדות — שם הגוף המפרסם בלבד.

══ כלל מיוחד למחקרי מרכז המחקר והמידע של הכנסת ══
אזכור כמאמר (כלל 24): שם החוקר (בלי תואר!) הוא המחבר. שם המאמר במירכאות. מרכז המחקר והמידע של הכנסת הוא הגוף המפרסם — מצוין בסוגריים לפני השנה.
דוגמה: עדי לוין "השלכות השינויים המוצעים לרפורמת המס בארצות הברית על ישראל" (מרכז המחקר והמידע של הכנסת, 2018).
שני חוקרים: יורם בלייזר וחן שוורץ "השוואת נטל המס" (מרכז המחקר והמידע של הכנסת, 2023).

══ סוגי מקורות ══
`;

  for (const rule of RULES) {
    output += `\n--- ${rule.ruleTitle} ---\n`;
    output += `תבנית: ${rule.template}\n`;
    output += `דוגמה: ${rule.example}\n`;
    output += `רכיבי חובה: ${rule.requiredFields.join("; ")}\n`;
    if (rule.formattingNotes.length > 0) {
      output += `הנחיות עיצוב:\n${rule.formattingNotes.map(n => `  • ${n}`).join("\n")}\n`;
    }
  }

  output += `
══ כללים נוספים ══
• אזכור חוזר (כלל 1.5): [שם מחבר/צדדים], לעיל הערה [מספר], בעמ' [עמוד].
• אזכור חוזר מיידי (כלל 1.6): שם, בעמ' [עמוד].
• הפניה לסעיף (כלל 2.8): ס' X, סס' X–Y.
• הפניה לפסקה (כלל 19.2): פס' X.

══ איסורים מוחלטים ══
• לעולם אל תשתמש ב-[missing:...] או [חסר:...] — אם אינך יודע פרט מסוים, השמט את הרכיב לגמרי.
• לעולם אל תציין תוארים (פרופ', ד"ר, עו"ד, רו"ח, שופט) בשמות מחברים או צדדים.
• לעולם אל תצטט בלוגים, אתרי משרדי עורכי דין, או מחברות לימודים בהערות שוליים.
• מספור הערות שוליים חייב להיות רציף ללא דילוגים (1, 2, 3...).
`;

  return output;
}
