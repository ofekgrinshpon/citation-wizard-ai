async function launch(id: string) {
  const r = await fetch(FN_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${ANON}`,
      apikey: ANON,
      "x-smoke-mode": "1",
      "x-smoke-token": TOKEN,
    },
    body: JSON.stringify({
      question: QUESTIONS[id],
      background: true,
      label: `batch3-${id}`,
    }),
  });
  const text = await r.text();
  console.log(id, r.status, text.slice(0, 300));
}

const ids = process.argv.slice(2).filter((a) => QUESTIONS[a]);
for (const id of ids) {
  await launch(id);
  await new Promise((res) => setTimeout(res, 1500));
}
