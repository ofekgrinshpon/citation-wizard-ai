"""Generate a bounded headings-only snapshot from the official German BGB XML."""
import hashlib
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree
from zipfile import ZipFile

SOURCE = "https://www.gesetze-im-internet.de/bgb/xml.zip"
NORM = "BJNR001950896"
path = Path(sys.argv[1])
with ZipFile(path) as z:
    member = z.getinfo(NORM + ".xml")
    if member.file_size > 4_000_000 or len(z.infolist()) != 1:
        raise ValueError("Unexpected archive size or shape")
    raw = z.read(member)
# The official doctype is a fixed external declaration. Do not fetch or expand it.
raw = raw.replace(b'<!DOCTYPE dokumente SYSTEM "https://www.gesetze-im-internet.de/dtd/1.01/gii-norm.dtd">', b"")
if b"<!DOCTYPE" in raw or b"<!ENTITY" in raw:
    raise ValueError("Unexpected XML declaration")
root = ElementTree.fromstring(raw)
stamp = root.get("builddate", "")
head = root.find("norm/metadaten")
if root.tag != "dokumente" or root.get("doknr") != NORM or not re.fullmatch(r"[0-9]{14}", stamp) or head is None or head.findtext("jurabk") != "BGB" or head.findtext("langue") != "Bürgerliches Gesetzbuch":
    raise ValueError("Not the official BGB")
titles = {}
for n in root.findall("norm/metadaten"):
    key = re.fullmatch(r"§ ([1-9]\d{0,3}[a-z]?)", n.findtext("enbez", ""))
    if key is None or n.findtext("jurabk") != "BGB":
        continue
    heading = n.find("titel")
    title = " ".join("".join(heading.itertext()).split()) if heading is not None else ""
    if not title or len(title) > 170 or re.search(r"[<>]|weggefallen|aufgehoben", title, re.I):
        continue
    if key[1] in titles:
        raise ValueError("Duplicate section " + key[1])
    titles[key[1]] = title
stamp = f"{stamp[:4]}-{stamp[4:6]}-{stamp[6:8]}"
print("// Generated by scripts/extract_bgb_titles.py; public government headings only.")
print("// Source: " + SOURCE + " SHA256=" + hashlib.sha256(path.read_bytes()).hexdigest())
print("export const BGB_SNAPSHOT_DATE = " + json.dumps(stamp) + ";")
print("export const BGB_TITLES: Readonly<Record<string,string>> = " + json.dumps(titles, ensure_ascii=False, sort_keys=True, indent=2) + ";")
